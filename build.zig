const std = @import("std");

// ---------------------------------------------------------------------------
// ISA tiers for the ported llama.cpp CPU quantization kernels (src/simd/).
//
// Zig 0.17 has no runtime function multiversioning (@setFunctionMCU /
// @optimizeFor are not in this compiler), so we do what Zig's own std does for
// multi-ISA code: compile the SAME source directory once per ISA tier, each
// with its own -mcpu, and pick a tier at runtime from CPUID.
//
// `addWriteFiles` materializes src/simd/ into the build cache under a per-tier
// subdirectory, with tier.zig replaced by that tier's name -- so tier.zig is
// the only file that differs, and kernels select their inner loop with comptime
// `if (isAvx512) ...`.  Each tier gets its own cache directory, which is what
// lets the same file belong to 3 modules.
//
// The directory is enumerated here at build-configuration time (not via
// addCopyDirectory: a copied file and an `add`ed file at the same path collide,
// and the copy wins, which would silently pin every tier to the committed
// "baseline" tier.zig).
// ---------------------------------------------------------------------------
const Tier = struct { name: []const u8, feats: []const std.Target.x86.Feature };

const tiers = [_]Tier{
    // Baseline: any x86-64. f16c+ssse3 are not in the x86-64-v1 baseline, so
    // the baseline tier requires them (matches llama.cpp's non-AVX path,
    // which also uses GGML_CPU_FP16_TO_FP32).
    .{ .name = "baseline", .feats = &.{ .ssse3, .f16c } },
    .{ .name = "avx2", .feats = &.{ .avx2, .fma, .f16c } },
    // AVX-512 tier: f/bw/vl/dq only.  Deliberately NOT avx512vnni -- many
    // AVX-512 parts (Skylake-X, Cascade Lake) lack VNNI, and enabling it lets
    // LLVM emit vdpbusd, which #UD's on those CPUs.  simd_dispatch gates a
    // future VNNI tier on the CPUID bit; kernels must not use vdpbusd unless
    // the tier name says so.
    .{ .name = "avx512", .feats = &.{ .avx512f, .avx512bw, .avx512vl, .avx512dq, .fma, .f16c } },
    // VNNI tier: superset of avx512 (f/bw/vl/dq) + avx512vnni.  Kernels that
    // use vpdpbusd (the int8 dot-product accumulators) are guarded by
    // `isAvx512Vnni` comptime gates, so this tier is the only one where the
    // inline-asm VNNI bodies compile; simd_dispatch binds it only when the
    // CPUID bit + XCR0 check pass.
    .{ .name = "avx512vnni", .feats = &.{ .avx512f, .avx512bw, .avx512vl, .avx512dq, .avx512vnni, .fma, .f16c } },
    // VBMI tier: VNNI set + avx512vbmi.  VBMI's cross-lane byte permutes
    // (vpermi2b/vpermb) are what the IQ kernels need to look up the 128-entry
    // ksigns/grid tables in-register; without them the sign lookup is a scalar
    // table read.  Gate on the CPUID bit (leaf 7, sub 0, EBX bit 31).
    .{ .name = "avx512vbmi", .feats = &.{ .avx512f, .avx512bw, .avx512vl, .avx512dq, .avx512vnni, .avx512vbmi, .fma, .f16c } },
};

/// Contents of the generated tier.zig for one ISA tier.
fn tierSource(comptime name: []const u8) []const u8 {
    return
        \\// Generated by build.zig -- do not edit.  This is the only file that
        \\// differs between the baseline / AVX2 / AVX512 compilations of
        \\// src/simd/.  `tier` is comptime-known, so the is* constants below are
        \\// comptime bools and tier-specific code is selected at compile time.
        \\const std = @import("std");
        \\pub const tier = "
    ++ name ++
        \\";
        \\pub const isBaseline = std.mem.eql(u8, tier, "baseline");
        \\pub const isAvx2 = std.mem.eql(u8, tier, "avx2");
        \\pub const isAvx512 = std.mem.eql(u8, tier, "avx512") or std.mem.eql(u8, tier, "avx512vnni") or std.mem.eql(u8, tier, "avx512vbmi");
        \\pub const isAvx512Vnni = std.mem.eql(u8, tier, "avx512vnni") or std.mem.eql(u8, tier, "avx512vbmi");
        \\pub const isAvx512Vbmi = std.mem.eql(u8, tier, "avx512vbmi");
        \\pub const lane_bytes = if (isAvx512) 64 else if (isAvx2) 32 else 16;
        \\
    ;
}

fn simdTier(b: *std.Build, comptime tier: Tier, target: std.Build.ResolvedTarget, optimize: std.builtin.OptimizeMode) *std.Build.Module {
    var add: std.Target.Cpu.Feature.Set = .empty;
    inline for (tier.feats) |f| add.addFeature(@intFromEnum(f));
    const wf = b.addWriteFiles();
    const dir = wf.addCopyDirectory(b.path("src/simd"), tier.name, .{});
    // src/simd/ deliberately contains NO tier.zig: a copied file and an added
    // file at the same path collide (the copy wins), which would silently pin
    // every tier to the committed baseline.  tier.zig exists only generated.
    const tfile = wf.add(tier.name ++ "/tier.zig", tierSource(tier.name));
    _ = tfile;
    const root: std.Build.LazyPath = .{ .generated = .{ .index = dir.generated.index, .sub_path = tier.name ++ "/root.zig" } };
    return b.createModule(.{
        .root_source_file = root,
        .target = b.resolveTargetQuery(.{
            .cpu_arch = target.query.cpu_arch orelse .x86_64,
            .os_tag = target.query.os_tag orelse .linux,
            .abi = target.query.abi,
            .cpu_features_add = add,
        }),
        .optimize = optimize,
    });
}

// Although this function looks imperative, it does not perform the build
// directly and instead it mutates the build graph (`b`) that will be then
// executed by an external runner. The functions in `std.Build` implement a DSL
// for defining build steps and express dependencies between them, allowing the
// build runner to parallelize the build automatically (and the cache system to
// know when a step doesn't need to be re-run).
pub fn build(b: *std.Build) void {
    // Standard target options allow the person running `zig build` to choose
    // what target to build for. Here we do not override the defaults, which
    // means any target is allowed, and the default is native. Other options
    // for restricting supported target set are available.
    const target = b.standardTargetOptions(.{});
    // Standard optimization options allow the person running `zig build` to select
    // between Debug, ReleaseSafe, ReleaseFast, and ReleaseSmall. Here we do not
    // set a preferred release mode, allowing the user to decide how to optimize.
    const optimize = b.standardOptimizeOption(.{});
    // It's also possible to define more custom flags to toggle optional features
    // of this build script using `b.option()`. All defined flags (including
    // target and optimize options) will be listed when running `zig build --help`
    // in this directory.

    // This creates a module, which represents a collection of source files alongside
    // some compilation options, such as optimization mode and linked system libraries.
    // Zig modules are the preferred way of making Zig code available to consumers.
    // addModule defines a module that we intend to make available for importing
    // to our consumers. We must give it a name because a Zig package can expose
    // multiple modules and consumers will need to be able to specify which
    // module they want to access.
    const mod = b.addModule("qwen35", .{
        // The root source file is the "entry point" of this module. Users of
        // this module will only be able to access public declarations contained
        // in this file, which means that if you have declarations that you
        // intend to expose to consumers that were defined in other files part
        // of this module, you will have to make sure to re-export them from
        // the root file.
        .root_source_file = b.path("src/root.zig"),
        // Later on we'll use this module as the root module of a test executable
        // which requires us to specify a target.
        .target = target,
    });

    // ---------------------------------------------------------------------------
    // C kernels for SIMD-optimized IQ quantization (ported from llama.cpp)
    // ---------------------------------------------------------------------------
    const c_kernels = b.addLibrary(.{
        .name = "iq_kernels",
        .linkage = .static,
        .root_module = b.createModule(.{
            .target = target,
            .optimize = optimize,
        }),
    });
    c_kernels.root_module.addCSourceFile(.{
        .file = b.path("src/c_kernels/iq_kernels.c"),
        .flags = &.{
            "-std=c11",
            "-O3",
            "-mavx2",
            "-mfma",
            "-mf16c",
        },
    });
    c_kernels.root_module.link_libc = true;
    b.installArtifact(c_kernels);

    // ISA-tier copies of the ported quantization kernels.  `mod` imports them
    // by name; simd/dispatch.zig binds the function pointers to whichever tier
    // the running CPU supports (CPUID + XGETBV, checked at runtime).
    inline for (tiers) |t| {
        mod.addImport("simd_" ++ t.name, simdTier(b, t, target, optimize));
    }

    // Here we define an executable. An executable needs to have a root module
    // which needs to expose a `main` function. While we could add a main function
    // to the module defined above, it's sometimes preferable to split business
    // logic and the CLI into two separate modules.
    //
    // If your goal is to create a Zig library for others to use, consider if
    // it might benefit from also exposing a CLI tool. A parser library for a
    // data serialization format could also bundle a CLI syntax checker, for example.
    //
    // If instead your goal is to create an executable, consider if users might
    // be interested in also being able to embed the core functionality of your
    // program in their own executable in order to avoid the overhead involved in
    // subprocessing your CLI tool.
    //
    // If neither case applies to you, feel free to delete the declaration you
    // don't need and to put everything under a single module.
    const exe = b.addExecutable(.{
        .name = "qwen35",
        .root_module = b.createModule(.{
            // b.createModule defines a new module just like b.addModule but,
            // unlike b.addModule, it does not expose the module to consumers of
            // this package, which is why in this case we don't have to give it a name.
            .root_source_file = b.path("src/main.zig"),
            // Target and optimization levels must be explicitly wired in when
            // defining an executable or library (in the root module), and you
            // can also hardcode a specific target for an executable or library
            // definition if desireable (e.g. firmware for embedded devices).
            .target = target,
            .optimize = optimize,
            // List of modules available for import in source files part of the
            // root module.
            .imports = &.{
                // Here "qwen35" is the name you will use in your source code to
                // import this module (e.g. `@import("qwen35")`). The name is
                // repeated because you are allowed to rename your imports, which
                // can be extremely useful in case of collisions (which can happen
                // importing modules from different packages).
                .{ .name = "qwen35", .module = mod },
            },
        }),
    });

    // Link C kernels library
    exe.root_module.linkLibrary(c_kernels);

    // This declares intent for the executable to be installed into the
    // install prefix when running `zig build` (i.e. when executing the default
    // step). By default the install prefix is `zig-out/` but can be overridden
    // by passing `--prefix` or `-p`.
    b.installArtifact(exe);

    // Dev-only CLI: tokenization diff tool against HF transformers.
    const tok_cli = b.addExecutable(.{
        .name = "qwen35-tok",
        .root_module = b.createModule(.{
            .root_source_file = b.path("src/tok_cli.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{
                .{ .name = "qwen35", .module = mod },
            },
        }),
    });
    b.installArtifact(tok_cli);

    // This creates a top level step. Top level steps have a name and can be
    // invoked by name when running `zig build` (e.g. `zig build run`).
    // This will evaluate the `run` step rather than the default step.
    // For a top level step to actually do something, it must depend on other
    // steps (e.g. a Run step, as we will see in a moment).
    const run_step = b.step("run", "Run the app");

    // This creates a RunArtifact step in the build graph. A RunArtifact step
    // invokes an executable compiled by Zig. Steps will only be executed by the
    // runner if invoked directly by the user (in the case of top level steps)
    // or if another step depends on it, so it's up to you to define when and
    // how this Run step will be executed. In our case we want to run it when
    // the user runs `zig build run`, so we create a dependency link.
    const run_cmd = b.addRunArtifact(exe);
    run_step.dependOn(&run_cmd.step);

    // By making the run step depend on the default step, it will be run from the
    // installation directory rather than directly from within the cache directory.
    run_cmd.step.dependOn(b.getInstallStep());

    // This allows the user to pass arguments to the application in the build
    // command itself, like this: `zig build run -- arg1 arg2 etc`.
    // Zig 0.17 removed the `b.args` field; the run step instead declares a
    // passthrough slot which the maker fills with the `-- ...` tail at run
    // time.
    run_cmd.addPassthruArgs();

    // Creates an executable that will run `test` blocks from the provided module.
    // Here `mod` needs to define a target, which is why earlier we made sure to
    // set the releative field.
    const mod_tests = b.addTest(.{
        .root_module = mod,
    });

    // A run step that will run the test executable.
    const run_mod_tests = b.addRunArtifact(mod_tests);

    // Creates an executable that will run `test` blocks from the executable's
    // root module. Note that test executables only test one module at a time,
    // hence why we have to create two separate ones.
    const exe_tests = b.addTest(.{
        .root_module = exe.root_module,
    });

    // A run step that will run the second test executable.
    const run_exe_tests = b.addRunArtifact(exe_tests);

    // A top level step for running all tests. dependOn can be called multiple
    // times and since the two run steps do not depend on one another, this will
    // make the two of them run in parallel.
    const test_step = b.step("test", "Run tests");
    test_step.dependOn(&run_mod_tests.step);
    test_step.dependOn(&run_exe_tests.step);

    // Just like flags, top level steps are also listed in the `--help` menu.
    //
    // The Zig build system is entirely implemented in userland, which means
    // that it cannot hook into private compiler APIs. All compilation work
    // orchestrated by the build system will result in other Zig compiler
    // subcommands being invoked with the right flags defined. You can observe
    // these invocations when one fails (or you pass a flag to increase
    // verbosity) to validate assumptions and diagnose problems.
    //
    // Lastly, the Zig build system is relatively simple and self-contained,
    // and reading its source code will allow you to master it.
}
