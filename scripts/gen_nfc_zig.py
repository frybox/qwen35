#!/usr/bin/env python3
"""Convert ref/c/nfc_table.h into src/nfc_table.zig.

The C header is the single source of truth for the NFC data (it is what the
reference implementation in ref/c compiles against); this script is a pure
format translation, it does not alter any values. Keeping the Zig tables
generated rather than hand-maintained means the two implementations cannot
silently drift apart.

Usage:
    python3 scripts/gen_nfc_zig.py            # regenerate src/nfc_table.zig
    python3 scripts/gen_nfc_zig.py --check    # verify it is up to date (no write)

Exit status is 0 on success, 1 on failure (--check reports a stale file).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = REPO_ROOT / "ref" / "c" / "nfc_table.h"
DEFAULT_OUTPUT = REPO_ROOT / "src" / "nfc_table.zig"

# `static const int nfc_pairs[][3] = { ... };`
_ARRAY_RE = {
    "pairs": re.compile(
        r"nfc_pairs\s*\[\s*\]\s*\[\s*3\s*\]\s*=\s*\{(?P<body>.*?)\n\s*\};",
        re.DOTALL,
    ),
    "single": re.compile(
        r"nfc_single\s*\[\s*\]\s*\[\s*2\s*\]\s*=\s*\{(?P<body>.*?)\n\s*\};",
        re.DOTALL,
    ),
}
_ROW_RE = {
    "pairs": re.compile(
        r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}"
    ),
    "single": re.compile(r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}"),
}


def parse_c_header(text: str) -> dict[str, list[tuple[int, ...]]]:
    """Extract the two tables from the C header as lists of int tuples.

    The C header spells both tables with a trailing `};` after the last row, so
    a non-greedy body match stops at the right place. Values are validated to
    be non-empty, sorted, and duplicate-free, because the Zig side binary-
    searches them.
    """
    tables: dict[str, list[tuple[int, ...]]] = {}
    for name, array_re in _ARRAY_RE.items():
        m = array_re.search(text)
        if m is None:
            raise SystemExit(f"error: could not find `nfc_{name}` array in the header")
        rows = [tuple(int(v, 16) for v in row) for row in _ROW_RE[name].findall(m["body"])]
        if not rows:
            raise SystemExit(f"error: `nfc_{name}` parsed as empty")

        width = 3 if name == "pairs" else 2
        bad = [r for r in rows if len(r) != width]
        if bad:
            raise SystemExit(f"error: `nfc_{name}` has a row with {len(bad[0])} values, expected {width}")

        if rows != sorted(rows):
            # The Zig tables are documented as sorted for binary search; the C
            # header is expected to already be sorted, so this signals an
            # upstream problem rather than something to fix silently here.
            raise SystemExit(f"error: `nfc_{name}` rows are not in ascending order")
        if len(rows) != len(set(rows)):
            raise SystemExit(f"error: `nfc_{name}` contains duplicate rows")

        tables[name] = rows
    return tables


def _fmt(cp: int) -> str:
    """Format a codepoint the way the existing Zig table does: `0x` + >=4 hex digits."""
    return f"0x{cp:04X}"


def render_zig(tables: dict[str, list[tuple[int, ...]]]) -> str:
    parts: list[str] = []
    parts.append("//! NFC (Normalization Form C) tables, converted from ref/c/nfc_table.h.")
    parts.append("//! Generated by scripts/gen_nfc_zig.py — do not edit by hand.")
    parts.append("")

    parts.append("/// Canonical composition pairs (starter, combining, composed),")
    parts.append("/// sorted by (starter, combining) for binary search.")
    parts.append("pub const pairs = [_][3]u32{")
    for a, b, c in tables["pairs"]:
        parts.append(f"    .{{ {_fmt(a)}, {_fmt(b)}, {_fmt(c)} }},")
    parts.append("};")
    parts.append("")

    parts.append("/// Single-codepoint canonical replacements (from, to), sorted by `from`.")
    parts.append("pub const single = [_][2]u32{")
    for a, b in tables["single"]:
        parts.append(f"    .{{ {_fmt(a)}, {_fmt(b)} }},")
    parts.append("};")
    parts.append("")

    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="C header to read")
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Zig file to write")
    ap.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the output file differs from the generated text",
    )
    args = ap.parse_args(argv)

    try:
        header_text = args.input.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot read {args.input}: {exc.strerror or exc}", file=sys.stderr)
        return 1

    tables = parse_c_header(header_text)
    generated = render_zig(tables).encode("utf-8")

    if args.check:
        try:
            current = args.output.read_bytes()
        except FileNotFoundError:
            print(f"STALE: {args.output} does not exist", file=sys.stderr)
            return 1
        if current != generated:
            print(f"STALE: {args.output} differs from generated output", file=sys.stderr)
            return 1
        print(f"OK: {args.output} is up to date")
        return 0

    args.output.write_bytes(generated)
    print(
        f"wrote {args.output} "
        f"({len(tables['pairs'])} pairs, {len(tables['single'])} single, {len(generated)} bytes)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
